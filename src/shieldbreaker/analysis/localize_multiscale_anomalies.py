#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""Locate EDR anomalies from event-level NLL sequences with adaptive thresholds.

The script implements the multi-scale localization rule:

    S(t) = max_w NLL_w(t), w in {256, 512, 1024}
    tau_p = Q_q({S_B(t)})
    anomalous if S_E(t) > tau_p

Inputs are the event-level files generated by export_endpoint_window_nll_matrix.py,
for example gpt2_medium_event_nll_sequence.json.
"""

import argparse
import json
import math
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Tuple


def load_events(path: Path) -> Tuple[Dict[str, object], List[Dict[str, object]]]:
    with path.open("r", encoding="utf-8") as f:
        payload = json.load(f)
    events = payload.get("events")
    if not isinstance(events, list):
        raise ValueError(f"{path} does not contain an 'events' list")
    return payload, events


def event_nlls(events: Sequence[Dict[str, object]]) -> List[float]:
    nlls: List[float] = []
    for idx, event in enumerate(events):
        try:
            value = float(event["nll"])
        except (KeyError, TypeError, ValueError) as exc:
            raise ValueError(f"Invalid nll at event index {idx}") from exc
        if math.isfinite(value):
            nlls.append(value)
        else:
            nlls.append(float("nan"))
    return nlls


def rolling_mean(values: Sequence[float], window: int) -> List[float]:
    if window <= 0:
        raise ValueError("window lengths must be positive")
    if not values:
        return []

    result = [float("nan")] * len(values)
    running_sum = 0.0
    valid_count = 0

    for idx, value in enumerate(values):
        if math.isfinite(value):
            running_sum += value
            valid_count += 1

        drop_idx = idx - window
        if drop_idx >= 0 and math.isfinite(values[drop_idx]):
            running_sum -= values[drop_idx]
            valid_count -= 1

        if idx >= window - 1 and valid_count > 0:
            # Assign the window score to its end position t.
            result[idx] = running_sum / valid_count

    return result


def multiscale_scores(values: Sequence[float], windows: Sequence[int]) -> List[Dict[str, object]]:
    per_window = {window: rolling_mean(values, window) for window in windows}
    scores: List[Dict[str, object]] = []

    for idx in range(len(values)):
        candidates = [
            (window, per_window[window][idx])
            for window in windows
            if idx < len(per_window[window]) and math.isfinite(per_window[window][idx])
        ]
        if not candidates:
            continue

        best_window, best_score = max(candidates, key=lambda item: item[1])
        scores.append(
            {
                "event_index": idx,
                "score": float(best_score),
                "best_window": int(best_window),
                "window_scores": {
                    str(window): float(score)
                    for window, score in candidates
                },
            }
        )

    return scores


def quantile(values: Sequence[float], q: float) -> float:
    finite = sorted(value for value in values if math.isfinite(value))
    if not finite:
        raise ValueError("Cannot compute a quantile from an empty score list")
    if not 0.0 <= q <= 1.0:
        raise ValueError("q must be in [0, 1]")

    pos = (len(finite) - 1) * q
    lo = int(math.floor(pos))
    hi = int(math.ceil(pos))
    if lo == hi:
        return float(finite[lo])
    weight = pos - lo
    return float(finite[lo] * (1.0 - weight) + finite[hi] * weight)


def score_stats(values: Sequence[float], q: float) -> Dict[str, float]:
    finite = [value for value in values if math.isfinite(value)]
    if not finite:
        return {"count": 0}
    mean = sum(finite) / len(finite)
    var = sum((value - mean) ** 2 for value in finite) / len(finite)
    return {
        "count": float(len(finite)),
        "mean": float(mean),
        "std": float(math.sqrt(var)),
        "min": float(min(finite)),
        "max": float(max(finite)),
        "q": float(q),
        "quantile": quantile(finite, q),
    }


def enrich_score(
    score: Dict[str, object],
    events: Sequence[Dict[str, object]],
    threshold: float,
) -> Dict[str, object]:
    idx = int(score["event_index"])
    event = events[idx] if 0 <= idx < len(events) else {}
    best_window = int(score["best_window"])
    start_event_index = max(0, idx - best_window + 1)

    return {
        "event_index": idx,
        "start_event_index": start_event_index,
        "end_event_index": idx,
        "best_window": best_window,
        "score": float(score["score"]),
        "threshold": float(threshold),
        "score_minus_threshold": float(score["score"]) - threshold,
        "window_scores": score["window_scores"],
        "raw_line_no": event.get("raw_line_no"),
        "timestamp": event.get("timestamp"),
        "pid": event.get("pid"),
        "tid": event.get("tid"),
        "event_uid": event.get("event_uid"),
        "method": event.get("method"),
        "unknown_token": event.get("unknown_token"),
    }


def merge_anomalies(
    anomalies: Sequence[Dict[str, object]],
    max_gap_events: int,
) -> List[Dict[str, object]]:
    if not anomalies:
        return []

    ordered = sorted(anomalies, key=lambda item: int(item["event_index"]))
    clusters: List[Dict[str, object]] = []
    current_items: List[Dict[str, object]] = [ordered[0]]

    def flush(items: Sequence[Dict[str, object]]) -> Dict[str, object]:
        peak = max(items, key=lambda item: float(item["score"]))
        return {
            "start_event_index": int(items[0]["start_event_index"]),
            "end_event_index": int(items[-1]["end_event_index"]),
            "event_count": int(items[-1]["end_event_index"]) - int(items[0]["start_event_index"]) + 1,
            "point_count": len(items),
            "peak_event_index": int(peak["event_index"]),
            "peak_score": float(peak["score"]),
            "peak_best_window": int(peak["best_window"]),
            "peak_method": peak.get("method"),
            "peak_timestamp": peak.get("timestamp"),
        }

    for item in ordered[1:]:
        prev = current_items[-1]
        if int(item["event_index"]) - int(prev["event_index"]) <= max_gap_events:
            current_items.append(item)
        else:
            clusters.append(flush(current_items))
            current_items = [item]

    clusters.append(flush(current_items))
    return clusters


def write_markdown(
    path: Path,
    product: str,
    threshold: float,
    windows: Sequence[int],
    anomalies: Sequence[Dict[str, object]],
    clusters: Sequence[Dict[str, object]],
    top_k: int,
) -> None:
    lines = [
        "# Multi-Scale Anomaly Localization",
        "",
        f"- Product: `{product}`",
        f"- Windows: `{', '.join(str(window) for window in windows)}`",
        f"- Adaptive threshold: `{threshold:.8f}`",
        f"- Anomaly points: `{len(anomalies)}`",
        f"- Anomaly clusters: `{len(clusters)}`",
        "",
        "## Top Anomaly Points",
        "",
    ]

    for item in sorted(anomalies, key=lambda row: float(row["score"]), reverse=True)[:top_k]:
        lines.extend(
            [
                f"### Event {item['event_index']}",
                "",
                f"- Score: `{float(item['score']):.8f}`",
                f"- Threshold: `{threshold:.8f}`",
                f"- Best window: `{item['best_window']}`",
                f"- Method: `{item.get('method')}`",
                f"- Timestamp: `{item.get('timestamp')}`",
                f"- Raw line: `{item.get('raw_line_no')}`",
                "",
            ]
        )

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def parse_windows(value: str) -> List[int]:
    windows = [int(part.strip()) for part in value.split(",") if part.strip()]
    if not windows:
        raise argparse.ArgumentTypeError("at least one window length is required")
    if any(window <= 0 for window in windows):
        raise argparse.ArgumentTypeError("window lengths must be positive")
    return sorted(set(windows))


def main(argv: Optional[Sequence[str]] = None) -> None:
    parser = argparse.ArgumentParser(description="Locate anomalies with multi-scale event NLL scores")
    parser.add_argument("--baseline", required=True, nargs="+", help="Baseline *_event_nll_sequence.json file(s)")
    parser.add_argument("--stimulated", required=True, help="Stimulated *_event_nll_sequence.json file")
    parser.add_argument("--product", required=True, help="Target EDR product name")
    parser.add_argument("--windows", type=parse_windows, default=parse_windows("256,512,1024"))
    parser.add_argument("--quantile", type=float, default=0.995, help="Baseline quantile used as tau_p")
    parser.add_argument("--max_gap_events", type=int, default=0, help="Merge anomalous points within this event gap")
    parser.add_argument("--top_k", type=int, default=50, help="Top anomaly points shown in Markdown")
    parser.add_argument("--output_json", required=True)
    parser.add_argument("--output_md", default=None)
    args = parser.parse_args(argv)

    baseline_paths = [Path(path).resolve() for path in args.baseline]
    stimulated_path = Path(args.stimulated).resolve()
    output_json = Path(args.output_json).resolve()
    output_md = Path(args.output_md).resolve() if args.output_md else output_json.with_suffix(".md")

    baseline_scores: List[float] = []
    baseline_inputs: List[Dict[str, object]] = []
    for path in baseline_paths:
        payload, events = load_events(path)
        scores = multiscale_scores(event_nlls(events), args.windows)
        baseline_scores.extend(float(item["score"]) for item in scores)
        baseline_inputs.append(
            {
                "path": str(path),
                "event_count": len(events),
                "score_count": len(scores),
                "input_path": payload.get("input_path"),
            }
        )

    threshold = quantile(baseline_scores, args.quantile)
    baseline_stats = score_stats(baseline_scores, args.quantile)

    stimulated_payload, stimulated_events = load_events(stimulated_path)
    stimulated_scores = multiscale_scores(event_nlls(stimulated_events), args.windows)
    anomalies = [
        enrich_score(score, stimulated_events, threshold)
        for score in stimulated_scores
        if float(score["score"]) > threshold
    ]
    clusters = merge_anomalies(anomalies, args.max_gap_events)

    output = {
        "product": args.product,
        "windows": args.windows,
        "quantile": args.quantile,
        "threshold": threshold,
        "baseline": {
            "inputs": baseline_inputs,
            "score_stats": baseline_stats,
        },
        "stimulated": {
            "path": str(stimulated_path),
            "input_path": stimulated_payload.get("input_path"),
            "event_count": len(stimulated_events),
            "score_count": len(stimulated_scores),
        },
        "anomaly_count": len(anomalies),
        "cluster_count": len(clusters),
        "anomalies": anomalies,
        "clusters": clusters,
    }

    output_json.parent.mkdir(parents=True, exist_ok=True)
    with output_json.open("w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=2)

    write_markdown(output_md, args.product, threshold, args.windows, anomalies, clusters, args.top_k)
    print(f"[OK] threshold={threshold:.8f}")
    print(f"[OK] anomalies={len(anomalies)} clusters={len(clusters)}")
    print(f"[OK] json={output_json}")
    print(f"[OK] md={output_md}")


if __name__ == "__main__":
    main()
